//! Conformance tests against the Go reference implementation
//! (<https://github.com/shenwei356/strobemers>).
//!
//! The two implementations use different ntHash libraries, so their k-mer hash
//! values differ numerically and cannot be compared directly. Instead, both are
//! driven by the same deterministic FNV-1a k-mer hasher ([`Fnv1a`], injected via
//! [`KmerHasher`]), which makes the *strobemer selection logic* — window bounds,
//! window shrinking, minimum selection, tie-breaking and hash mixing —
//! comparable value by value.
//!
//! The expected tuples below were produced by the Go reference with
//! `computeHashes` replaced by the same FNV-1a function.
//!
//! Every case here is one where the Rust implementation is expected to agree
//! with Go exactly. The one deliberate deviation (Go emitting trailing
//! strobemers whose second window is empty) is covered by
//! `empty_second_window_ends_iteration` in `tests/port_conformance.rs`.

use strobemers_rs::{KmerHasher, MinStrobes, RandStrobes, Result};

/// Deterministic 64-bit FNV-1a over each k-mer, mirroring the patched Go harness.
struct Fnv1a;

impl KmerHasher for Fnv1a {
    fn hash_all(&self, seq: &[u8], k: usize) -> Result<Vec<u64>> {
        Ok(seq
            .windows(k)
            .map(|w| {
                let mut h: u64 = 14695981039346656037;
                for &b in w {
                    h ^= b as u64;
                    h = h.wrapping_mul(1099511628211);
                }
                h
            })
            .collect())
    }
}

