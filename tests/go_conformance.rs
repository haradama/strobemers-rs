/// Drives every case through the matching iterator and compares strobe indices
/// and hash values against the Go reference output, element by element.
#[test]
fn matches_go_reference() -> Result<()> {
    for case in CASES {
        let label = format!(
            "seq_len={} n={} l={} w_min={} w_max={} shrink={}",
            case.seq.len(),
            case.n,
            case.l,
            case.w_min,
            case.w_max,
            case.shrink
        );

        let mut got: Vec<(usize, usize, usize, u64)> = Vec::new();
        match case.kind {
            Kind::Rand => {
                let mut it = RandStrobes::with_hasher(
                    case.seq, case.n, case.l, case.w_min, case.w_max, &Fnv1a,
                )?;
                it.set_window_shrink(case.shrink);
                while let Some(h) = it.next() {
                    let [m1, m2, m3] = it.indexes();
                    got.push((m1, m2, m3, h));
                }
            }
            Kind::Min => {
                let mut it = MinStrobes::with_hasher(
                    case.seq, case.n, case.l, case.w_min, case.w_max, &Fnv1a,
                )?;
                it.set_window_shrink(case.shrink);
                while let Some(h) = it.next() {
                    let [m1, m2, m3] = it.indexes();
                    got.push((m1, m2, m3, h));
                }
            }
        }

        assert_eq!(
            got.len(),
            case.expected.len(),
            "strobemer count differs from Go reference ({label})"
        );
        for (i, (g, w)) in got.iter().zip(case.expected).enumerate() {
            assert_eq!(g, w, "item {i} differs from Go reference ({label})");
        }
    }
    Ok(())
}
